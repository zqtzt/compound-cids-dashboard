export const dictionaries = {en, zh};
export function tr(lang, key) { return dictionaries[lang]?.[key] ?? en[key] ?? key; }
export function formatCoordinate(lon, lat) {
  const lonText = Math.abs(lon).toFixed(1) + '°' + (lon < 0 ? 'W' : 'E');
  const latText = Math.abs(lat).toFixed(1) + '°' + (lat < 0 ? 'S' : 'N');
  return latText + '  ' + lonText;
}
export function exposureLabel(lang, value) {
  if (value === 1) return '—';
  return tr(lang, ({1: 'low', 2: 'medium', 3: 'high'})[value] || 'noValue');
}
export function confidenceLabel(lang, value) {
  return tr(lang, value === 1 ? 'passed' : value === 0 ? 'notPassed' : 'notAssessed');
}
